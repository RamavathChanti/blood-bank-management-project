import { test, expect } from "@playwright/test";
test("bounded mass casualty model supports stop, reset and deterministic critical priority", async ({ page }, info) => {
  const errors: string[] = []; const registryWrites: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (r.method() === "POST" && /\/api\/(emergencies|registry)/.test(r.url())) registryWrites.push(r.url()); });
  await page.goto("/surge-lab");
  await expect(page.getByRole("heading", { name: "Surge Lab", exact: true })).toBeVisible();
  await expect(page.getByRole("navigation").getByRole("link", { name: "Surge Lab", exact: true })).toHaveAttribute("aria-current", "page");
  await page.getByLabel("Requests", { exact: true }).fill("21"); await page.getByRole("button", { name: "Run bounded surge" }).click();
  await expect(page.getByRole("status")).toContainText("Ready for a bounded surge");
  await page.getByLabel("Requests", { exact: true }).fill("12");
  await page.getByRole("button", { name: "Run bounded surge" }).click();
  await expect(page.getByRole("status")).toContainText("Simulation running");
  await page.getByRole("button", { name: "Stop surge" }).click();
  await expect(page.getByRole("status")).toContainText("Simulation stopped");
  const frozen = await page.getByLabel("Synthetic queue").innerText(); await page.waitForTimeout(350); expect(await page.getByLabel("Synthetic queue").innerText()).toBe(frozen);
  await page.getByRole("button", { name: "Reset surge" }).click(); await expect(page.getByLabel("Synthetic queue")).toHaveCount(0);
  await page.getByLabel("Requests", { exact: true }).fill("6"); await page.getByRole("button", { name: "Run bounded surge" }).click();
  await expect(page.getByRole("status")).toHaveText("Simulation complete", { timeout: 10000 });
  await expect(page.getByText("Step complete", { exact: true })).toHaveCount(6);
  const queue = page.getByLabel("Synthetic queue");
  await expect(queue.locator("article").filter({ hasText: "synthetic-5" })).toContainText("Started at 900 model ms");
  await expect(queue.locator("article").filter({ hasText: "synthetic-3" })).toContainText("Started at 1,700 model ms");
  expect(registryWrites).toEqual([]); expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `../_ai_context/artifacts/stage-13-surge-${info.project.name}.png`, fullPage: true });
});
